let byPostcode: Map<string, string> | undefined;

/** The town of a Danish postcode, e.g. "8000" → "Aarhus C", or null when it is not in use. */
export function townForPostcode(postcode: string): string | null {
  byPostcode ??= new Map(TOWNS.flatMap(([town, codes]) => codes.split(" ").map((code) => [code, town] as const)));
  return byPostcode.get(postcode.trim()) ?? null;
}

/**
 * "By" after the postcode changed: the postcode's town when the field is empty or still holds
 * the town filled in before (`filled`), else what the customer typed. Danish addresses only.
 */
export function cityForPostcode(input: { country: string; postcode: string; city: string; filled: string | null }): { city: string; filled: string | null } {
  const town = input.country === "DK" && /^\d{4}$/.test(input.postcode) ? townForPostcode(input.postcode) : null;
  if (town && (input.city.trim() === "" || input.city === input.filled)) return { city: town, filled: town };
  return { city: input.city, filled: input.filled };
}
